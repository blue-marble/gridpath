    def test_exports_components_only_for_zones_with_penalty(self):
        """
        The exports variable and its constraint are only built for load
        zones with a non-zero export penalty; the penalty cost expression
        is 0 elsewhere.
        """
        m, data = add_components_and_load_data(
            prereq_modules=IMPORTED_PREREQ_MODULES,
            module_to_test=MODULE_BEING_TESTED,
            test_data_dir=TEST_DATA_DIRECTORY,
            weather_iteration="",
            hydro_iteration="",
            availability_iteration="",
            subproblem="",
            stage="",
        )

        # The fixture has no export penalties
        instance = m.create_instance(data)
        self.assertEqual(len(instance.EXPORT_PENALTY_LZ_TMPS), 0)
        self.assertEqual(len(instance.LZ_Exports), 0)
        self.assertEqual(len(instance.Positive_Exports_Tuning_Cost_Constraint), 0)
        self.assertEqual(
            {
                value(instance.Export_Penalty_Cost[lz, tmp])
                for lz in instance.LOAD_ZONES
                for tmp in instance.TMPS
            },
            {0},
        )

        # With a penalty in one zone
        data["export_penalty_cost_per_mwh"]["Zone1"] = 5
        instance = m.create_instance(data)
        expected = {("Zone1", tmp) for tmp in instance.TMPS}
        self.assertEqual(set(instance.EXPORT_PENALTY_LZ_TMPS), expected)
        self.assertEqual(set(instance.LZ_Exports.keys()), expected)
        self.assertEqual(
            set(instance.Positive_Exports_Tuning_Cost_Constraint.keys()), expected
        )
